import shutil
from pathlib import Path

from pipeline.providers.base import Provider, ProviderError


class ACEStepProvider(Provider):
    provider_name = "kaggle-ace-step"
    output_extension = ".wav"

    def __init__(self, output: Path | None) -> None:
        self.output = output

    def model_for(self, kind: str) -> str:
        return "ACE-Step-v1.5"

    def generate(self, request: dict) -> str:
        if not self.output or not self.output.is_file():
            raise ProviderError("Set ACE_STEP_OUTPUT to the original music file generated by the notebook")
        destination = Path(request["output"])
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(self.output, destination)
        return str(destination)
